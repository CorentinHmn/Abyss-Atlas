import { cpSync, existsSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { describe, expect, it } from "vitest";
import { main } from "./main";

const REFERENCE = resolve(import.meta.dirname, "../../../examples/reference");

async function run(args: string[], cwd = REFERENCE) {
  let out = "";
  let err = "";
  const code = await main(args, { out: (t) => (out += t), err: (t) => (err += t), cwd, today: () => "2026-11-05" });
  return { code, out, err };
}

describe("atlas CLI (UC-034)", () => {
  it("validates the reference project", async () => {
    const { code, out } = await run(["validate"]);
    expect(code).toBe(0);
    expect(out).toContain("✓ Valid: 0 error(s), 11 warning(s).");
  });

  it("fails on an invalid project with exit code 1", async () => {
    const copy = mkdtempSync(join(tmpdir(), "atlas-"));
    cpSync(REFERENCE, copy, { recursive: true });
    const path = join(copy, "models/GOV/dim_plant.yaml");
    writeFileSync(path, readFileSync(path, "utf8").replace("t.WERKS\n", "t.NOPE\n"));
    const result = await run(["validate", copy]);
    expect(result.code).toBe(1);
    expect(result.out).toContain("error VAL-020");
    const generated = await run(["generate", "dbt", copy, "--out", join(copy, "out")]);
    expect(generated.code).toBe(1);
    expect(generated.err).toContain("Not generated");
  });

  it("generates dbt and docs, and removes outdated generated files", async () => {
    const out = mkdtempSync(join(tmpdir(), "atlas-dbt-"));
    writeFileSync(join(out, "old.sql"), "-- Generated by Atlas from an older version\n");
    writeFileSync(join(out, "mine.sql"), "-- written by hand\n");
    const dbt = await run(["generate", "dbt", "--out", out]);
    expect(dbt.code).toBe(0);
    expect(dbt.out).toContain("1 outdated file(s) removed");
    expect(existsSync(join(out, "models/SEL/dim_customer.sql"))).toBe(true);
    expect(existsSync(join(out, "old.sql"))).toBe(false);
    expect(existsSync(join(out, "mine.sql"))).toBe(true);
    const docs = await run(["generate", "docs", "--out", join(out, "docs")]);
    expect(docs.code).toBe(0);
    expect(existsSync(join(out, "docs/index.md"))).toBe(true);
  });

  it("imports a dictionary file into a project", async () => {
    const copy = mkdtempSync(join(tmpdir(), "atlas-"));
    cpSync(REFERENCE, copy, { recursive: true });
    writeFileSync(join(copy, "dict.csv"), "dataset;column;native_type\nKNA1;KUNNR;CHAR(10)\nKNA1;BRSCH;CHAR(4)\n");
    const result = await run(["import", "dictionary", "dict.csv", "--system", "sap_fr", "--dialect", "sap"], copy);
    expect(result.code).toBe(0);
    expect(result.out).toContain("0 dataset(s) created, 1 updated");
    expect(readFileSync(join(copy, "systems/sap_fr/datasets/kna1.yaml"), "utf8")).toContain("BRSCH");
    expect((await run(["validate"], copy)).code).toBe(0);
    const diff = await run(["diff", REFERENCE, copy]);
    expect(diff.out).toContain("~ dataset sap_fr.kna1");
    expect(diff.out).toContain("columns.BRSCH");
  });

  it("explains its usage", async () => {
    expect((await run(["--help"])).out).toContain("atlas generate dbt");
    expect((await run(["frobnicate"])).code).toBe(1);
  });
});
