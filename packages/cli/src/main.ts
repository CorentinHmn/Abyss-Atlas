/**
 * Atlas command line (docs/05-modules/import-export.md §5, UC-034). Works offline, without an account (IE-040).
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { parseArgs } from "node:util";
import {
  DIALECTS,
  diffProjects,
  generateDbt,
  generateDocs,
  importDictionary,
  loadProject,
  validateProject,
  type Dialect,
  type GeneratedFile,
  type Issue,
  type SpecFile,
} from "@atlas/core";

export interface Io {
  out: (text: string) => void;
  err: (text: string) => void;
  cwd: string;
  /** Date of today (YYYY-MM-DD), injectable for tests. */
  today: () => string;
}

declare const __ATLAS_VERSION__: string | undefined;
const VERSION = typeof __ATLAS_VERSION__ === "string" ? __ATLAS_VERSION__ : "dev";

const HELP = `Atlas ${VERSION}: source-to-target specifications as code.

Usage:
  atlas validate [dir] [--format text|json]
      Validates the project in dir (default: current folder). Exit code 1 when there is an error.
  atlas generate dbt [dir] --out <dir>
      Writes the dbt project for the project's target platform (Snowflake).
  atlas generate docs [dir] --out <dir>
      Writes the Markdown documentation.
  atlas import dictionary <file.csv> --system <id> --dialect <${DIALECTS.join("|")}> [dir] [--date YYYY-MM-DD]
      Creates or updates the source datasets of a system from a dictionary file.
  atlas diff <dir-a> <dir-b> [--format text|json]
      Lists the objects added, removed and changed between two versions of a project.

A project folder is an Atlas export: it holds atlas.yaml (docs/03-spec-format.md).
`;

const SKIPPED_FOLDERS = new Set(["node_modules", "target", "dbt_packages", "logs"]);

function readProjectFolder(root: string): SpecFile[] {
  const files: SpecFile[] = [];
  const walk = (dir: string) => {
    for (const entry of readdirSync(dir)) {
      if (entry.startsWith(".") || SKIPPED_FOLDERS.has(entry)) continue;
      const full = join(dir, entry);
      if (statSync(full).isDirectory()) walk(full);
      else if (entry.endsWith(".yaml")) files.push({ path: relative(root, full).split(sep).join("/"), content: readFileSync(full, "utf8") });
    }
  };
  walk(root);
  return files;
}

function formatIssue(issue: Issue): string {
  return `${issue.file}${issue.at ? `  ${issue.at}` : ""}\n  ${issue.severity} ${issue.code}: ${issue.message}`;
}

/** Writes generated files and removes files generated earlier that are no longer produced. */
function writeGenerated(outDir: string, files: GeneratedFile[]): { written: number; removed: number } {
  const keep = new Set(files.map((file) => resolve(outDir, file.path)));
  let removed = 0;
  if (existsSync(outDir)) {
    const walk = (dir: string) => {
      for (const entry of readdirSync(dir)) {
        if (entry === "target" || entry === "dbt_packages") continue;
        const full = join(dir, entry);
        if (statSync(full).isDirectory()) walk(full);
        else if (!keep.has(resolve(full)) && readFileSync(full, "utf8").slice(0, 300).includes("Generated by Atlas")) {
          rmSync(full);
          removed += 1;
        }
      }
    };
    walk(outDir);
  }
  for (const file of files) {
    const path = resolve(outDir, file.path);
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, file.content);
  }
  return { written: files.length, removed };
}

function requireProject(io: Io, dir: string): boolean {
  if (existsSync(join(dir, "atlas.yaml"))) return true;
  io.err(`No atlas.yaml in ${dir}: this is not an Atlas project folder.\n`);
  return false;
}

export async function main(argv: string[], io: Io): Promise<number> {
  const { values, positionals } = parseArgs({
    args: argv,
    allowPositionals: true,
    options: {
      out: { type: "string" },
      system: { type: "string" },
      dialect: { type: "string" },
      date: { type: "string" },
      format: { type: "string", default: "text" },
      help: { type: "boolean", short: "h" },
      version: { type: "boolean", short: "v" },
    },
  });
  const [command, ...rest] = positionals;
  if (values.version) {
    io.out(`${VERSION}\n`);
    return 0;
  }
  if (values.help || !command) {
    io.out(HELP);
    return command || values.help ? 0 : 1;
  }
  const json = values.format === "json";

  if (command === "validate") {
    const dir = resolve(io.cwd, rest[0] ?? ".");
    if (!requireProject(io, dir)) return 1;
    const result = validateProject(readProjectFolder(dir));
    if (json) io.out(`${JSON.stringify({ errors: result.errors, warnings: result.warnings, unstructuredShare: result.unstructuredShare, issues: result.issues }, null, 2)}\n`);
    else {
      for (const issue of result.issues) io.out(`${formatIssue(issue)}\n`);
      io.out(`${result.errors === 0 ? "✓ Valid" : "✗ Invalid"}: ${result.errors} error(s), ${result.warnings} warning(s). Unstructured logic: ${(result.unstructuredShare * 100).toFixed(1)} % of the target columns.\n`);
    }
    return result.errors === 0 ? 0 : 1;
  }

  if (command === "generate") {
    const [what, dirArg] = rest;
    if (what !== "dbt" && what !== "docs") {
      io.err("Usage: atlas generate dbt|docs [dir] --out <dir>\n");
      return 1;
    }
    if (!values.out) {
      io.err("Missing --out <dir>: the folder to write to.\n");
      return 1;
    }
    const dir = resolve(io.cwd, dirArg ?? ".");
    if (!requireProject(io, dir)) return 1;
    const result = validateProject(readProjectFolder(dir));
    if (result.errors > 0) {
      for (const issue of result.issues.filter((i) => i.severity === "error")) io.err(`${formatIssue(issue)}\n`);
      io.err(`✗ Not generated: the project has ${result.errors} validation error(s) (VAL-000).\n`);
      return 1;
    }
    const files = what === "dbt" ? generateDbt(result) : generateDocs(result);
    const outDir = resolve(io.cwd, values.out);
    const { written, removed } = writeGenerated(outDir, files);
    io.out(`✓ ${what === "dbt" ? "dbt project" : "Documentation"} written to ${relative(io.cwd, outDir) || "."}: ${written} file(s)${removed ? `, ${removed} outdated file(s) removed` : ""}.\n`);
    return 0;
  }

  if (command === "import") {
    const [what, csvArg, dirArg] = rest;
    if (what !== "dictionary" || !csvArg) {
      io.err("Usage: atlas import dictionary <file.csv> --system <id> --dialect <dialect> [dir]\n");
      return 1;
    }
    const dialect = values.dialect as Dialect | undefined;
    if (!values.system || !dialect || !DIALECTS.includes(dialect)) {
      io.err(`Give --system <id> and --dialect <${DIALECTS.join("|")}>.\n`);
      return 1;
    }
    const dir = resolve(io.cwd, dirArg ?? ".");
    const existing = existsSync(join(dir, "atlas.yaml"))
      ? new Map([...loadProject(readProjectFolder(dir)).project.datasets.values()].filter((d) => d.spec.system === values.system).map((d) => [d.spec.id, d.spec]))
      : new Map();
    const csvPath = resolve(io.cwd, csvArg);
    if (!existsSync(csvPath)) {
      io.err(`File not found: ${csvArg}\n`);
      return 1;
    }
    const { files, report } = importDictionary({ csv: readFileSync(csvPath, "utf8"), system: values.system, dialect, existing, date: values.date ?? io.today(), method: "cli_import" });
    if (report.errors.length > 0) {
      for (const error of report.errors) io.err(`✗ ${error}\n`);
      return 1;
    }
    writeGenerated(dir, files);
    io.out(`✓ ${report.created.length} dataset(s) created, ${report.updated.length} updated in systems/${values.system}/datasets.\n`);
    for (const unknown of report.unknownTypes) io.out(`  ! ${unknown.dataset}.${unknown.column}: native type "${unknown.nativeType}" not recognized, imported as string. Fix its type.\n`);
    for (const missing of report.missingColumns) io.out(`  ! ${missing.dataset}.${missing.column} is not in the file any more: kept, delete it in Atlas if it is gone.\n`);
    if (!existsSync(join(dir, "systems", values.system, "system.yaml"))) io.out(`  ! systems/${values.system}/system.yaml does not exist yet: create the system.\n`);
    return 0;
  }

  if (command === "diff") {
    const [a, b] = rest;
    if (!a || !b) {
      io.err("Usage: atlas diff <dir-a> <dir-b>\n");
      return 1;
    }
    const before = loadProject(readProjectFolder(resolve(io.cwd, a))).project;
    const after = loadProject(readProjectFolder(resolve(io.cwd, b))).project;
    const changes = diffProjects(before, after);
    if (json) io.out(`${JSON.stringify(changes, null, 2)}\n`);
    else {
      for (const change of changes) {
        io.out(`${{ added: "+", removed: "-", changed: "~" }[change.change]} ${change.kind} ${change.key}\n`);
        for (const field of change.fields) io.out(`    ${field.path}: ${JSON.stringify(field.before)} → ${JSON.stringify(field.after)}\n`);
      }
      io.out(`${changes.length} object(s) differ.\n`);
    }
    return 0;
  }

  io.err(`Unknown command "${command}".\n\n${HELP}`);
  return 1;
}
