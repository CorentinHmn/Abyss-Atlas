/**
 * dbt generator for Snowflake (docs/05-modules/generation.md, UC-030).
 * Input: a project without validation errors (GEN-001). Output: files, byte-identical for the same project (GEN-002).
 */
import type { Project } from "../spec/load";
import type { Condition, DatasetSpec, Mapping, ModelSpec, Operand, Step } from "../spec/schemas";
import { FUNCTIONS, type ValueType } from "../types/functions";
import { formatLogicalType, isNumeric, parseLogicalType, type LogicalType } from "../types/logical-types";
import type { ValidationResult } from "../validate/validate";
import { quoteIdentifier, quoteText, renderFunction, renderLiteral, snowflakeType } from "./sql";

export interface GeneratedFile {
  path: string;
  content: string;
}

export class GenerationError extends Error {}

/**
 * An SQL expression with its type when known, or a literal waiting for its context (GEN §2.4).
 * `exact` means Snowflake is sure to give it exactly that type (a source column, an explicit conversion).
 */
type Expr = { sql: string; type?: LogicalType; exact?: boolean } | { literal: string };

interface SourceInfo {
  columns: Map<string, LogicalType>;
  isModel: boolean;
}

interface BranchContext {
  project: Project;
  /** Spec alias → SQL alias and columns. */
  aliases: Map<string, { sqlAlias: string; source: SourceInfo }>;
  /** Left joins added by lookup steps. */
  lookupJoins: string[];
  lookupCount: { value: number };
  /** Rule parameters bound to SQL expressions (inline expansion of rules). */
  params?: Map<string, Expr>;
  /** Data tests needed by fail behaviors (GEN-021). */
  failChecks: { label: string; select: string; where: string }[];
  /** FROM + joins + filter of the branch, for the fail checks. */
  fromClause: () => string;
}

const mustType = (text: string): LogicalType => {
  const type = parseLogicalType(text);
  if (!type) throw new GenerationError(`Invalid type ${text}.`);
  return type;
};

const HEADER = (projectId: string) => `Generated by Atlas from project "${projectId}" (format 1). Do not edit: change the spec in Atlas instead.`;

function render(expr: Expr, context?: LogicalType): string {
  return "literal" in expr ? renderLiteral(expr.literal, context) : expr.sql;
}

function typeOf(expr: Expr | undefined): LogicalType | undefined {
  return expr && "type" in expr ? expr.type : undefined;
}

function toValueType(expr: Expr): ValueType {
  if ("literal" in expr) return { literal: expr.literal };
  return expr.type ? { type: expr.type } : { unknown: true };
}

function sourceOf(project: Project, ref: string): SourceInfo {
  const dataset = project.datasets.get(ref);
  if (dataset) return { columns: new Map(Object.entries(dataset.spec.columns).map(([name, column]) => [name, mustType(column.type)])), isModel: false };
  const model = project.models.get(ref);
  if (model) {
    const columns = new Map(Object.entries(model.spec.columns).map(([name, column]) => [name, mustType(column.type)]));
    if (model.spec.consolidation?.add_source_column) columns.set(model.spec.consolidation.add_source_column, { kind: "string", length: 20 });
    return { columns, isModel: true };
  }
  throw new GenerationError(`Unknown dataset or model ${ref}.`);
}

function relation(project: Project, ref: string): string {
  const dataset = project.datasets.get(ref);
  if (dataset) return `{{ source('${dataset.spec.system}', '${dataset.spec.id}') }}`;
  return `{{ ref('${ref}') }}`;
}

