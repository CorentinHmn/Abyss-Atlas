const yamlText = (value: string): string => JSON.stringify(value.trim().replace(/\s+/g, " "));

function testsFor(model: ModelSpec, name: string, project: Project): string[] {
  const col = model.columns[name];
  if (!col) return [];
  const tests: string[] = [];
  const push = (test: string, args: string[] = [], severity?: string) => {
    if (args.length === 0 && severity !== "warn") {
      tests.push(`          - ${test}`);
      return;
    }
    tests.push(`          - ${test}:`);
    if (args.length > 0) tests.push("              arguments:", ...args.map((arg) => `                ${arg}`));
    if (severity === "warn") tests.push("              config:", "                severity: warn");
  };
  // GEN-060: grain keys and required columns are checked even when the spec does not say so.
  const isGrainKey = model.grain.key.includes(name);
  const plain = new Set<string>();
  if (!col.nullable || isGrainKey) plain.add("not_null");
  if (isGrainKey && model.grain.key.length === 1) plain.add("unique");
  for (const check of col.quality ?? []) if (check === "not_null" || check === "unique") plain.add(check);
  for (const test of [...plain].sort()) push(test);
  for (const check of col.quality ?? []) {
    if (typeof check === "string") continue;
    if ("not_null" in check && !plain.has("not_null")) push("not_null", [], check.not_null.severity);
    if ("unique" in check && !plain.has("unique")) push("unique", [], check.unique.severity);
    if ("accepted_values" in check) {
      const values = check.accepted_values.values ?? Object.values(project.valueMappings.get(check.accepted_values.mapping ?? "")?.spec.entries ?? {});
      push("accepted_values", [`values: [${[...new Set(values)].map((v) => JSON.stringify(v)).join(", ")}]`], check.accepted_values.severity);
    }
    if ("relationship" in check) {
      const [target = "", field = ""] = check.relationship.to.split(".");
      push("relationships", [`to: ref('${target}')`, `field: ${field}`], check.relationship.severity);
    }
  }
  return tests.length ? ["        data_tests:", ...tests] : [];
}

function schemaYaml(project: Project, model: ModelSpec): string {
  const projectId = project.project?.spec.id ?? "project";
  const lines = [`# ${HEADER(projectId)}`, "version: 2", "models:", `  - name: ${model.id}`, `    description: ${yamlText(`${model.name}. ${model.description} Grain: ${model.grain.description}`)}`, "    columns:"];
  for (const [name, col] of Object.entries(model.columns)) {
    lines.push(`      - name: ${name}`, `        description: ${yamlText(col.definition)}`, `        data_type: ${snowflakeType(mustType(col.type))}`, ...testsFor(model, name, project));
  }
  if (model.consolidation?.add_source_column) {
    lines.push(`      - name: ${model.consolidation.add_source_column}`, `        description: ${yamlText("Source system of the row (automatic column, MM-133).")}`, "        data_type: varchar(20)");
  }
  return `${lines.join("\n")}\n`;
}

function uniqueCombinationTests(project: Project, model: ModelSpec): GeneratedFile[] {
  const projectId = project.project?.spec.id ?? "project";
  const combos: { columns: string[]; label: string }[] = [];
  if (model.grain.key.length > 1) combos.push({ columns: model.grain.key, label: "grain" });
  for (const check of model.quality ?? []) {
    if (typeof check === "object" && "unique_combination" in check) combos.push({ columns: check.unique_combination.columns, label: `unique_${check.unique_combination.columns.join("_")}` });
  }
  return combos.map(({ columns, label }) => ({
    path: `tests/atlas/${model.id}__${label}.sql`,
    content: `-- ${HEADER(projectId)}\n-- ${model.id}: ${columns.join(", ")} must be unique together. Returns the duplicates.\nselect ${columns.join(", ")}, count(*) as row_count\nfrom {{ ref('${model.id}') }}\ngroup by ${columns.join(", ")}\nhaving count(*) > 1\n`,
  }));
}

function sourcesYaml(project: Project, systemId: string, datasets: DatasetSpec[]): string {
  const system = project.systems.get(systemId)?.spec;
  if (!system?.landing) throw new GenerationError(`System ${systemId} has no landing location (GEN §2.1).`);
  const projectId = project.project?.spec.id ?? "project";
  const lines = [
    `# ${HEADER(projectId)}`,
    "version: 2",
    "sources:",
    `  - name: ${systemId}`,
    `    description: ${yamlText(`${system.name}${system.product ? ` (${system.product})` : ""}. ${system.description ?? ""}`)}`,
    `    database: ${system.landing.database}`,
    `    schema: ${system.landing.schema}`,
    "    tables:",
  ];
  for (const dataset of [...datasets].sort((a, b) => a.id.localeCompare(b.id))) {
    lines.push(`      - name: ${dataset.id}`, `        identifier: ${dataset.landing_name ?? dataset.name}`, `        description: ${yamlText(dataset.description ?? dataset.name)}`, "        columns:");
    for (const [name, col] of Object.entries(dataset.columns)) {
      lines.push(`          - name: ${name}`, "            quote: true", `            description: ${yamlText(`${col.description ?? name} (${col.native_type ?? formatLogicalType(mustType(col.type))})`)}`);
    }
  }
  return `${lines.join("\n")}\n`;
}

/** UC-030: the dbt project of a valid project (GEN-001…GEN-061). */
export function generateDbt(result: ValidationResult): GeneratedFile[] {
  if (result.errors > 0) throw new GenerationError(`The project has ${result.errors} validation error(s): fix them before generating (VAL-000).`);
  const { project } = result;
  const projectId = project.project?.spec.id ?? "project";
  const files: GeneratedFile[] = [
    {
      path: "dbt_project.yml",
      content: [
        `# ${HEADER(projectId)}`,
        `name: atlas_${projectId.replace(/-/g, "_")}`,
        'version: "1.0.0"',
        "config-version: 2",
        "profile: atlas",
        'model-paths: ["models"]',
        'test-paths: ["tests"]',
        "",
      ].join("\n"),
    },
  ];

  const used = new Set<string>();
  for (const { spec } of project.models.values()) {
    for (const branch of Object.values(spec.branches)) for (const use of branch.datasets) for (const ref of Object.values(use)) if (project.datasets.has(ref)) used.add(ref);
    for (const col of Object.values(spec.columns))
      for (const mapping of Object.values(col.from))
        if (typeof mapping === "object" && "steps" in mapping)
          for (const step of mapping.steps ?? []) if (typeof step === "object" && "lookup" in step && project.datasets.has(step.lookup.dataset)) used.add(step.lookup.dataset);
  }
  const bySystem = new Map<string, DatasetSpec[]>();
  for (const ref of used) {
    const dataset = project.datasets.get(ref)?.spec;
    if (dataset) bySystem.set(dataset.system, [...(bySystem.get(dataset.system) ?? []), dataset]);
  }
  for (const systemId of [...bySystem.keys()].sort()) {
    files.push({ path: `models/sources/${systemId}.yml`, content: sourcesYaml(project, systemId, bySystem.get(systemId) ?? []) });
  }

  for (const id of [...project.models.keys()].sort()) {
    const model = project.models.get(id)?.spec;
    if (!model) continue;
    const { sql, failTests } = modelSql(project, model);
    files.push({ path: `models/${model.domain}/${model.id}.sql`, content: sql });
    files.push({ path: `models/${model.domain}/${model.id}.yml`, content: schemaYaml(project, model) });
    files.push(...uniqueCombinationTests(project, model), ...failTests);
  }
  return files.sort((a, b) => a.path.localeCompare(b.path));
}

