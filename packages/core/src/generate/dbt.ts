function column(ctx: BranchContext, ref: string): Expr {
  const [alias = "", name = ""] = ref.split(".");
  const entry = ctx.aliases.get(alias);
  if (!entry) throw new GenerationError(`Unknown alias ${alias}.`);
  const type = entry.source.columns.get(name);
  const sql = entry.source.isModel ? `${entry.sqlAlias}.${name}` : `${entry.sqlAlias}.${quoteIdentifier(name)}`;
  return type ? { sql, type, exact: true } : { sql };
}

function operand(ctx: BranchContext, value: Operand, current: Expr | undefined): Expr {
  if (typeof value === "string") {
    if (value === "current") {
      if (!current) throw new GenerationError("No current value.");
      return current;
    }
    return column(ctx, value);
  }
  if ("value" in value) return { literal: value.value };
  if ("param" in value) {
    const bound = ctx.params?.get(value.param);
    if (!bound) throw new GenerationError(`Unknown parameter ${value.param}.`);
    return bound;
  }
  return calculation(ctx, value.calculate, current);
}

function calculation(ctx: BranchContext, calc: { function: string; args: Operand[] }, current: Expr | undefined): Expr {
  const signature = FUNCTIONS[calc.function];
  if (!signature) throw new GenerationError(`Unknown function ${calc.function}.`);
  const args = calc.args.map((arg) => operand(ctx, arg, current));
  const numericContext: LogicalType = { kind: "decimal", precision: 38, scale: 10 };
  const sqlArgs = args.map((arg, index) => {
    const kind = signature.args[index] ?? signature.rest ?? "any";
    if ("literal" in arg) {
      if (kind === "number" || kind === "integer_literal") return renderLiteral(arg.literal, numericContext);
      if (kind === "unit") return arg.literal;
      if (kind === "date") return renderLiteral(arg.literal, { kind: "date" });
      const typed = args.find((other) => "type" in other && other.type);
      return renderLiteral(arg.literal, typeOf(typed));
    }
    return arg.sql;
  });
  const result = signature.result(args.map(toValueType));
  const sql = renderFunction(calc.function, sqlArgs);
  return "type" in result ? { sql, type: result.type } : { sql };
}

const OPERATORS: Record<string, string> = { eq: "=", ne: "<>", lt: "<", le: "<=", gt: ">", ge: ">=", like: "like" };

function condition(ctx: BranchContext, c: Condition, current: Expr | undefined): string {
  if ("all" in c) return `(${c.all.map((child) => condition(ctx, child, current)).join(" and ")})`;
  if ("any" in c) return `(${c.any.map((child) => condition(ctx, child, current)).join(" or ")})`;
  if ("not" in c) return `not (${condition(ctx, c.not, current)})`;
  if ("sql" in c) return `(${c.sql.replace(/\{\{\s*current\s*\}\}/g, current ? `(${render(current)})` : "null")})`;
  const left = operand(ctx, c.left, current);
  const right = c.right !== undefined ? operand(ctx, c.right, current) : undefined;
  const context = typeOf(left) ?? typeOf(right);
  const l = render(left, typeOf(right) ?? context);
  switch (c.op) {
    case "is_null":
      return `${l} is null`;
    case "is_not_null":
      return `${l} is not null`;
    case "in":
    case "not_in":
      return `${l} ${c.op === "in" ? "in" : "not in"} (${(c.values ?? []).map((v) => renderLiteral(v, context)).join(", ")})`;
    case "between": {
      const [low = "", high = ""] = c.values ?? [];
      return `${l} between ${renderLiteral(low, context)} and ${renderLiteral(high, context)}`;
    }
    default: {
      const r = right !== undefined ? render(right, context) : renderLiteral(c.value ?? "", context);
      return `${l} ${OPERATORS[c.op] ?? "="} ${r}`;
    }
  }
}

function steps(ctx: BranchContext, list: Step[], start: Expr | undefined, label: string): Expr | undefined {
  let current = start;
  const need = (): Expr => {
    if (!current) throw new GenerationError(`${label}: no current value.`);
    return current;
  };

  for (const step of list) {
    if (step === "copy") continue;
    if ("constant" in step) {
      current = { literal: step.constant.value };
    } else if ("default" in step) {
      const value = need();
      const type = typeOf(value);
      const fallback = renderLiteral(step.default.value, type);
      const base = step.default.also_empty && (!type || type.kind === "string") ? `nullif(trim(${render(value)}), '')` : render(value);
      current = { sql: `coalesce(${base}, ${fallback})`, ...(type ? { type } : {}) };
    } else if ("convert" in step) {
      const value = need();
      const to = mustType(step.convert.to);
      const target = snowflakeType(to);
      const inputIsText = typeOf(value)?.kind === "string" || "literal" in value;
      const strict = step.convert.on_error === "fail";
      const text = render(value);
      let sql: string;
      if (step.convert.method === "parse") {
        const pattern = step.convert.pattern ? `, ${quoteText(step.convert.pattern)}` : "";
        if (to.kind === "date") sql = `${strict ? "to_date" : "try_to_date"}(${text}${pattern})`;
        else if (to.kind === "timestamp" || to.kind === "timestamp_tz") sql = `${strict ? "to_timestamp" : "try_to_timestamp"}(${text}${pattern})`;
        else if (isNumeric(to)) sql = `${strict ? "to_number" : "try_to_number"}(${text}, 38, ${to.kind === "decimal" ? to.scale : 0})`;
        else sql = `${strict || !inputIsText ? "cast" : "try_cast"}(${text} as ${target})`;
      } else if (step.convert.method === "format") {
        sql = `to_char(${text}${step.convert.pattern ? `, ${quoteText(step.convert.pattern)}` : ""})`;
      } else {
        sql = `${strict || !inputIsText ? "cast" : "try_cast"}(${text} as ${target})`;
      }
      if (step.convert.on_error === "use_default" && step.convert.default !== undefined) {
        sql = `coalesce(${sql}, ${renderLiteral(step.convert.default, to)})`;
      }
      current = { sql, type: to, exact: step.convert.method !== "format" };
    } else if ("map_values" in step) {
      const value = need();
      const mapping = ctx.project.valueMappings.get(step.map_values.mapping);
      if (!mapping) throw new GenerationError(`Unknown value mapping ${step.map_values.mapping}.`);
      const from = mustType(mapping.spec.from_type);
      const to = mustType(mapping.spec.to_type);
      const input = render(value, from);
      const whens = Object.entries(mapping.spec.entries ?? {})
        .map(([key, target]) => `when ${input} = ${renderLiteral(key, from)} then ${renderLiteral(target, to)}`)
        .join(" ");
      const unmatched = step.map_values.on_unmatched;
      const otherwise =
        unmatched === "keep" ? input : unmatched === "use_default" && mapping.spec.default !== undefined ? renderLiteral(mapping.spec.default, to) : "null";
      if (unmatched === "fail") {
        ctx.failChecks.push({
          label: `unmatched values of ${mapping.spec.id}`,
          select: `${input} as unmatched_value`,
          where: `${input} is not null and ${input} not in (${Object.keys(mapping.spec.entries ?? {}).map((key) => renderLiteral(key, from)).join(", ")})`,
        });
      }
      current = { sql: `/* value mapping ${mapping.spec.id} */ case when ${input} is null then null ${whens} else ${otherwise} end`, type: to };
    } else if ("case" in step) {
      const results = step.case.when.map((branch) => operand(ctx, branch.then, current));
      const fallback = step.case.else !== undefined ? operand(ctx, step.case.else, current) : undefined;
      const resultType = [...results, ...(fallback ? [fallback] : [])].map(typeOf).find((type) => type !== undefined);
      const whens = step.case.when.map((branch, index) => `when ${condition(ctx, branch.if, current)} then ${render(results[index] as Expr, resultType)}`).join(" ");
      current = { sql: `case ${whens} else ${fallback ? render(fallback, resultType) : "null"} end`, ...(resultType ? { type: resultType } : {}) };
    } else if ("calculate" in step) {
      current = calculation(ctx, step.calculate, current);
    } else if ("concat" in step) {
      const parts = step.concat.parts.map((part) => operand(ctx, part, current));
      const isTextLiteral = (sql: string) => /^'(?:[^']|'')*'$/.test(sql);
      const sqlParts = parts.map((part) =>
        "literal" in part ? quoteText(part.literal) : isTextLiteral(part.sql) ? part.sql : `nullif(cast(${part.sql} as varchar), '')`,
      );
      current = { sql: `array_to_string(array_construct_compact(${sqlParts.join(", ")}), ${quoteText(step.concat.separator ?? "")})`, type: { kind: "string" } };
    } else if ("lookup" in step) {
      const lookup = step.lookup;
      ctx.lookupCount.value += 1;
      const sqlAlias = `${lookup.alias}_lk${ctx.lookupCount.value}`;
      const source = sourceOf(ctx.project, lookup.dataset);
      const local: BranchContext = { ...ctx, aliases: new Map([...ctx.aliases, [lookup.alias, { sqlAlias, source }]]) };
      const match = condition(local, lookup.match, current);
      ctx.lookupJoins.push(`left join ${relation(ctx.project, lookup.dataset)} as ${sqlAlias}\n        on ${match}`);
      const returned = column(local, lookup.return);
      if (lookup.on_missing === "fail") {
        ctx.failChecks.push({
          label: `rows without a match in ${lookup.dataset}`,
          select: "*",
          where: `not exists (select 1 from ${relation(ctx.project, lookup.dataset)} as ${sqlAlias} where ${match})`,
        });
      }
      current =
        lookup.on_missing === "use_default" && lookup.default !== undefined
          ? { sql: `coalesce(${render(returned)}, ${renderLiteral(lookup.default, typeOf(returned))})`, ...(typeOf(returned) ? { type: typeOf(returned) as LogicalType } : {}) }
          : returned;
    } else if ("aggregate" in step) {
      const value = render(need());
      const type = typeOf(current);
      const fn = step.aggregate;
      const sql = fn === "count_distinct" ? `count(distinct ${value})` : `${fn}(${value})`;
      current = fn === "count" || fn === "count_distinct" ? { sql, type: { kind: "bigint" } } : { sql, ...(type ? { type } : {}) };
    } else if ("rule" in step) {
      const rule = ctx.project.rules.get(step.rule.id);
      if (!rule) throw new GenerationError(`Unknown rule ${step.rule.id}.`);
      const params = new Map<string, Expr>();
      for (const [name, typeText] of Object.entries(rule.spec.parameters)) {
        const arg = step.rule.args[name];
        if (arg === undefined) throw new GenerationError(`Missing argument ${name} of ${rule.spec.id}.`);
        const bound = operand(ctx, arg, current);
        params.set(name, "literal" in bound ? { sql: renderLiteral(bound.literal, mustType(typeText)), type: mustType(typeText) } : bound);
      }
      const only = params.size === 1 ? [...params.values()][0] : undefined;
      const inner: BranchContext = { ...ctx, params };
      const result = steps(inner, rule.spec.logic, only, `rule ${rule.spec.id}`);
      if (!result) throw new GenerationError(`Rule ${rule.spec.id} produces no value.`);
      current = { sql: `/* rule ${rule.spec.id} */ (${render(result, mustType(rule.spec.returns))})`, type: mustType(rule.spec.returns) };
    } else if ("sql" in step) {
      const sql = step.sql.expression.replace(/\{\{\s*current\s*\}\}/g, current ? `(${render(current)})` : "null");
      current = { sql: `/* sql: ${step.sql.reason.trim().replace(/\*\//g, "* /")} */ (${sql})` };
    }
  }
  return current;
}

/** The SQL of a column mapping, cast to the target type unless it already has exactly that type (GEN-022). */
function mappingExpr(ctx: BranchContext, mapping: Mapping, target: LogicalType, label: string): string {
  let result: Expr | undefined;
  if (typeof mapping === "string") result = column(ctx, mapping);
  else if ("not_provided" in mapping) result = { sql: "null" };
  else {
    const inputs = mapping.inputs ?? [];
    const start = inputs.length === 1 && inputs[0] ? column(ctx, inputs[0]) : undefined;
    result = steps(ctx, mapping.steps ?? [], start, label);
  }
  if (!result) throw new GenerationError(`${label} produces no value.`);
  const type = typeOf(result);
  const sql = render(result, target);
  const exact = "exact" in result && result.exact === true;
  return exact && type && snowflakeType(type) === snowflakeType(target) ? sql : `cast(${sql} as ${snowflakeType(target)})`;
}

