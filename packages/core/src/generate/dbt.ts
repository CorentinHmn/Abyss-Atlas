interface BranchSql {
  id: string;
  cte: string;
  failChecks: BranchContext["failChecks"];
  from: string;
}

function branchSql(project: Project, model: ModelSpec, branchId: string, priority: number): BranchSql {
  const branch = model.branches[branchId];
  if (!branch) throw new GenerationError(`Unknown branch ${branchId}.`);
  const aliases = new Map<string, { sqlAlias: string; source: SourceInfo }>();
  for (const use of branch.datasets) {
    const [alias = "", ref = ""] = Object.entries(use)[0] ?? [];
    aliases.set(alias, { sqlAlias: alias, source: sourceOf(project, ref) });
  }
  const uses = branch.datasets.map((use) => Object.entries(use)[0] ?? ["", ""]);
  const [driverAlias = "", driverRef = ""] = uses[0] ?? [];
  const introduced = new Set([driverAlias]);
  const joinLines: string[] = [];

  const ctx: BranchContext = {
    project,
    aliases,
    lookupJoins: [],
    lookupCount: { value: 0 },
    failChecks: [],
    fromClause: () => "",
  };
  for (const join of branch.joins ?? []) {
    const reversed = introduced.has(join.right) && !introduced.has(join.left);
    const newAlias = reversed ? join.left : join.right;
    const ref = uses.find(([alias]) => alias === newAlias)?.[1];
    if (!ref) throw new GenerationError(`Join on unknown alias ${newAlias}.`);
    const type = reversed ? ({ left: "right", right: "left", inner: "inner", full: "full" } as const)[join.type] : join.type;
    joinLines.push(`${type === "inner" ? "inner" : `${type}`} join ${relation(project, ref)} as ${newAlias}\n        on ${condition(ctx, join.condition, undefined)}`);
    introduced.add(newAlias);
  }

  const columnLines = Object.entries(model.columns).map(([name, col]) => {
    const target = mustType(col.type);
    const mapping = col.from[branchId] ?? col.from["*"];
    if (mapping === undefined) throw new GenerationError(`No mapping for ${name} in ${branchId}.`);
    return `${mappingExpr(ctx, mapping, target, `${model.id}.${name} (${branchId})`)} as ${name}`;
  });
  // Technical columns used by the union and the consolidation; only the source tag can reach the result (MM-133).
  columnLines.push(`${quoteText(branch.source_tag ?? branchId)} as atlas_source_tag`, `${quoteText(branchId)} as atlas_branch`, `${priority} as atlas_priority`);

  const fromLines = [`from ${relation(project, driverRef)} as ${driverAlias}`, ...joinLines.map((line) => line), ...ctx.lookupJoins];
  const where = branch.filter ? `where ${condition(ctx, branch.filter, undefined)}` : "";
  const groupBy = branch.group_by ? `group by ${branch.group_by.map((ref) => render(column(ctx, ref))).join(", ")}` : "";
  let qualify = "";
  if (branch.deduplicate) {
    const flip = branch.deduplicate.keep === "last";
    const order = (branch.deduplicate.order_by ?? []).map((o) => `${render(column(ctx, o.column))} ${(o.direction === "asc") !== flip ? "asc" : "desc"}`);
    qualify = `qualify row_number() over (partition by ${branch.deduplicate.key.map((ref) => render(column(ctx, ref))).join(", ")}${order.length ? ` order by ${order.join(", ")}` : ""}) = 1`;
  }
  const from = [...fromLines, where].filter(Boolean).join("\n");
  const body = [`select\n        ${columnLines.join(",\n        ")}`, ...fromLines, where, groupBy, qualify].filter(Boolean).join("\n    ");
  return { id: branchId, cte: `branch_${branchId} as (\n    ${body}\n)`, failChecks: ctx.failChecks, from };
}

function modelSql(project: Project, model: ModelSpec): { sql: string; failTests: GeneratedFile[] } {
  const projectId = project.project?.spec.id ?? "project";
  const branchIds = Object.keys(model.branches);
  const consolidation = model.consolidation;
  const priorities = consolidation?.survivorship?.priority ?? branchIds;
  const branches = branchIds.map((id) => branchSql(project, model, id, priorities.indexOf(id) + 1));
  const columns = Object.keys(model.columns);
  const sourceColumn = consolidation?.add_source_column;
  const finalColumns = [...columns, ...(sourceColumn ? [`atlas_source_tag as ${sourceColumn}`] : [])];
  const ctes = branches.map((b) => b.cte);
  let finalFrom: string;

  if (branches.length === 1) {
    finalFrom = `branch_${branchIds[0]}`;
  } else if (!consolidation?.match) {
    const distinct = consolidation?.combine === "union_distinct";
    if (distinct && sourceColumn) throw new GenerationError(`${model.id}: add_source_column cannot be combined with union_distinct yet.`);
    const selected = distinct ? columns.join(", ") : "*";
    ctes.push(`unioned as (\n    ${branches.map((b) => `select ${selected} from branch_${b.id}`).join(`\n    union${distinct ? "" : " all"}\n    `)}\n)`);
    finalFrom = "unioned";
  } else {
    const match = consolidation.match;
    ctes.push(`unioned as (\n    ${branches.map((b) => `select * from branch_${b.id}`).join("\n    union all\n    ")}\n)`);
    const partition = `partition by ${match.join(", ")}`;
    const branchOrder = (list: string[]) => `case atlas_branch ${list.map((id, i) => `when ${quoteText(id)} then ${i + 1}`).join(" ")} else ${list.length + 1} end`;
    const survived = columns.map((name) => {
      const strategy = consolidation.survivorship?.columns?.[name];
      if (!strategy) return name;
      const order = strategy.priority ?? priorities;
      if (strategy.strategy === "first_not_null") return `first_value(${name}) ignore nulls over (${partition} order by ${branchOrder(order)}) as ${name}`;
      if (strategy.strategy === "priority") return `first_value(${name}) over (${partition} order by ${branchOrder(order)}) as ${name}`;
      if (strategy.strategy === "most_recent") return `first_value(${name}) over (${partition} order by ${strategy.by} desc nulls last) as ${name}`;
      throw new GenerationError(`${model.id}.${name}: survivorship by rule is not generated yet.`);
    });
    const filled = match.map((name) => `${name} is not null`).join(" and ");
    const empty = match.map((name) => `${name} is null`).join(" or ");
    ctes.push(
      `matched as (\n    select\n        ${[...survived, "atlas_source_tag", `row_number() over (${partition} order by atlas_priority) as atlas_rank`].join(",\n        ")}\n    from unioned\n    where ${filled}\n)`,
      `consolidated as (\n    select ${[...columns, "atlas_source_tag"].join(", ")} from matched where atlas_rank = 1\n    union all\n    -- MM-132: rows without a match key are never merged\n    select ${[...columns, "atlas_source_tag"].join(", ")} from unioned where ${empty}\n)`,
    );
    finalFrom = "consolidated";
  }

  const materialized = model.materialization ?? project.project?.spec.defaults?.materialization ?? "table";
  const sql = [
    `-- ${HEADER(projectId)}`,
    `-- ${model.name}: ${model.description.trim().replace(/\s+/g, " ")}`,
    `{{ config(materialized='${materialized}') }}`,
    "",
    `with\n\n${ctes.join(",\n\n")}\n`,
    `select\n    ${finalColumns.join(",\n    ")}\nfrom ${finalFrom}\n`,
  ].join("\n");

  const failTests = branches.flatMap((b) =>
    b.failChecks.map((check, index) => ({
      path: `tests/atlas/${model.id}__${b.id}__fail_${index + 1}.sql`,
      content: `-- ${HEADER(projectId)}\n-- ${model.id}, branch ${b.id}: ${check.label}. Returns the offending rows; the test fails when there is any.\nselect ${check.select}\n${b.from}\n${/\nwhere /.test(b.from) ? "and" : "where"} ${check.where}\n`,
    })),
  );
  return { sql, failTests };
}

