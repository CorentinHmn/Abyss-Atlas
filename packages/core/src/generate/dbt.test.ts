import { describe, expect, it } from "vitest";
import { readProject, REFERENCE_PROJECT } from "../testing/read-project";
import { validateProject } from "../validate/validate";
import { generateDbt, GenerationError } from "./dbt";

const files = generateDbt(validateProject(readProject(REFERENCE_PROJECT)));
const file = (path: string): string => {
  const found = files.find((f) => f.path === path);
  if (!found) throw new Error(`No generated file ${path}. Files: ${files.map((f) => f.path).join(", ")}`);
  return found.content;
};

describe("dbt generation of the reference project (UC-030)", () => {
  it("writes the project, one source file per system and one SQL + YAML pair per model", () => {
    const paths = files.map((f) => f.path);
    expect(paths).toContain("dbt_project.yml");
    expect(paths.filter((p) => p.startsWith("models/sources/"))).toEqual([
      "models/sources/mes.yml",
      "models/sources/oracle.yml",
      "models/sources/sap_de.yml",
      "models/sources/sap_fr.yml",
    ]);
    expect(paths.filter((p) => /^models\/(SEL|MFG|GOV)\/.*\.sql$/.test(p))).toHaveLength(7);
    expect(paths.filter((p) => /^models\/(SEL|MFG|GOV)\/.*\.yml$/.test(p))).toHaveLength(7);
  });

  it("is deterministic (GEN-002)", () => {
    expect(generateDbt(validateProject(readProject(REFERENCE_PROJECT)))).toEqual(files);
  });

  it("marks every file as generated (GEN-003)", () => {
    for (const f of files) expect(f.content).toContain("Generated by Atlas");
  });

  it("refuses a project with validation errors (GEN-001)", () => {
    const broken = readProject(REFERENCE_PROJECT).map((f) =>
      f.path === "models/GOV/dim_plant.yaml" ? { ...f, content: f.content.replace("t.WERKS\n", "t.NOPE\n") } : f,
    );
    expect(() => generateDbt(validateProject(broken))).toThrow(GenerationError);
  });

  it("reads sources from their landing location with their real names", () => {
    const sapFr = file("models/sources/sap_fr.yml");
    expect(sapFr).toContain("database: RAW");
    expect(sapFr).toContain("schema: SAP_FR");
    expect(sapFr).toContain("identifier: KNA1");
  });

  it("consolidates customers on the VAT number, never merging rows without one (GEN-031, MM-132)", () => {
    const sql = file("models/SEL/dim_customer.sql");
    expect(sql).toContain("row_number() over (partition by vat_number order by atlas_priority)");
    expect(sql).toContain("first_value(credit_limit) ignore nulls over (partition by vat_number order by case atlas_branch when 'oracle' then 1");
    expect(sql).toContain("from unioned where vat_number is null");
    expect(sql).toContain("atlas_source_tag as source_system");
  });

  it("chains models with ref() and aggregates grouped branches (GEN-010, GEN-020)", () => {
    expect(file("models/MFG/fact_production_order.sql")).toContain("{{ ref('int_mes_order_output') }} as x");
    const mes = file("models/MFG/int_mes_order_output.sql");
    expect(mes).toContain("group by w.\"ERP_ORDER_REF\"");
    expect(mes).toContain("sum(coalesce(w.\"QTY_GOOD\", 0))");
  });

  it("expands rules inline, with a marker", () => {
    expect(file("models/GOV/fact_exchange_rate.sql")).toContain("/* rule sap_inverted_date */ (to_date(cast((99999999 - cast(r.\"GDATU\" as number(38,0))) as varchar(8)), 'YYYYMMDD'))");
  });

  it("turns fail behaviors into data tests that list the offending rows (GEN-021)", () => {
    const failTests = files.filter((f) => f.path.includes("__fail_"));
    expect(failTests.map((f) => f.path)).toEqual([
      "tests/atlas/fact_exchange_rate__sap_fr__fail_1.sql",
      "tests/atlas/fact_sales_order_line__oracle__fail_1.sql",
      "tests/atlas/fact_sales_order_line__oracle__fail_2.sql",
    ]);
    expect(file("tests/atlas/fact_exchange_rate__sap_fr__fail_1.sql")).toContain("not in ('M', 'EURX', 'P')");
  });

  it("writes tests from quality checks and grain keys (GEN-060, GEN-061)", () => {
    const yml = file("models/SEL/fact_sales_order_line.yml");
    expect(yml).toContain("to: ref('dim_customer')");
    expect(yml).toContain("severity: warn");
    expect(file("tests/atlas/fact_exchange_rate__grain.sql")).toContain("having count(*) > 1");
  });

  it("generates dim_plant exactly as reviewed", () => {
    expect(file("models/GOV/dim_plant.sql")).toMatchSnapshot();
  });
});
