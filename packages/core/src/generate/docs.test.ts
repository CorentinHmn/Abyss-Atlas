import { describe, expect, it } from "vitest";
import { readProject, REFERENCE_PROJECT } from "../testing/read-project";
import { validateProject } from "../validate/validate";
import { generateDocs } from "./docs";

const files = generateDocs(validateProject(readProject(REFERENCE_PROJECT)));
const file = (path: string) => files.find((f) => f.path === path)?.content ?? "";

describe("Markdown documentation of the reference project (UC-032)", () => {
  it("writes an index, one page per model, rule and value mapping", () => {
    expect(files.filter((f) => f.path.startsWith("models/"))).toHaveLength(7);
    expect(files.filter((f) => f.path.startsWith("rules/"))).toHaveLength(5);
    expect(files.filter((f) => f.path.startsWith("value-mappings/"))).toHaveLength(5);
    expect(file("index.md")).toContain("## SEL — Sales");
    expect(file("index.md")).toContain("Unstructured logic (SQL escape hatches): 1.6 %");
  });

  it("explains each column, source by source, in plain words (GEN-070)", () => {
    const page = file("models/SEL/dim_customer.md");
    expect(page).toContain("| Column | Type | Definition | SAP France | SAP Germany | Oracle EBS |");
    expect(page).toContain("KNA1.LAND1 → converted to string(2)");
    expect(page).toContain("*not provided*: Held in the SAP credit management module");
    expect(page).toContain("The same entity is recognized by vat_number; rows without it are never merged.");
  });

  it("links rules and value mappings", () => {
    expect(file("models/SEL/dim_customer.md")).toContain("translated with [customer_segment_sap](../../value-mappings/customer_segment_sap.md)");
    expect(file("rules/sap_inverted_date.md")).toContain("99999999 minus YYYYMMDD");
  });

  it("marks every page as generated (GEN-003)", () => {
    for (const f of files) expect(f.content.startsWith("<!-- Generated by Atlas")).toBe(true);
  });
});
